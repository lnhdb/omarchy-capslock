const M=require('../Model.js'),a=require('assert')
const kb=(name,capsLock,main)=>({name,layout:'us',options:'compose:caps,shift:both_capslock_cancel',active_keymap:'English (US)',capsLock,numLock:true,main})
const devices=(...k)=>JSON.stringify({mice:[],keyboards:k,tablets:[],touch:[],switches:[]})
a.strictEqual(M.capsOn(devices(kb('power-button',false,false),kb('cornix',false,true))),false,'all off')
a.strictEqual(M.capsOn(devices(kb('cornix',false,false),kb('capslock-test-kbd',true,true))),true,'real Hyprland 0.56.2: only the keyboard that locked it reports capsLock')
a.strictEqual(M.capsOn(devices(kb('cornix',true,false),kb('fcitx5-virtual',false,true))),true,'counts when main is another keyboard')
a.strictEqual(M.capsOn(devices()),false,'no keyboards')
a.strictEqual(M.capsOn(''),null,'killed or failed hyprctl')
a.strictEqual(M.capsOn('HYPRLAND_INSTANCE_SIGNATURE not set!'),null,'hyprctl error text')
a.strictEqual(M.capsOn('{"ok":true}'),null,'not a device list')
console.log('ok')
